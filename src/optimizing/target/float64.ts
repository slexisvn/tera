export function doubleBits(value: number): bigint {
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, value);
  return view.getBigUint64(0);
}

export const FLOAT64_MANTISSA_BITS = 52;
export const FLOAT64_SIGN_SHIFT = 63;
export const FLOAT64_EXPONENT_MASK = 0x7ff;
export const FLOAT64_MANTISSA_MASK = (1n << BigInt(FLOAT64_MANTISSA_BITS)) - 1n;

export const FLOAT64_EXPONENT_BIAS = 1075;
export const FLOAT64_MIN_EXPONENT = 1 - FLOAT64_EXPONENT_BIAS;

export const FLOAT64_SIGNIFICANT_DIGITS = 17;
export const FLOAT64_FIXED_EXPONENT_LIMIT = 21;
export const FLOAT64_FRACTION_EXPONENT_LIMIT = -6;
export const FLOAT64_EXPONENT_DIGITS = String(FLOAT64_EXPONENT_BIAS).length;

export const FLOAT64_LIMB_BITS = 32;
export const FLOAT64_LIMB_BYTES = FLOAT64_LIMB_BITS / 8;

const FLOAT64_SCALE_BITS =
  FLOAT64_EXPONENT_BIAS +
  FLOAT64_MANTISSA_BITS +
  Math.ceil(FLOAT64_SIGNIFICANT_DIGITS * Math.log2(10));

export const FLOAT64_LIMBS = Math.ceil(FLOAT64_SCALE_BITS / FLOAT64_LIMB_BITS) + 1;

export const FLOAT64_DECIMAL_BYTES =
  "-0.".length -
  FLOAT64_FRACTION_EXPONENT_LIMIT +
  FLOAT64_SIGNIFICANT_DIGITS +
  1;

export const FLOAT64_NULL_BITS = 0x7ff8_0000_0000_0001n;

export const FLOAT64_BIGNUM_LENGTH_BYTES = 8;
export const FLOAT64_BIGNUM_BYTES =
  FLOAT64_BIGNUM_LENGTH_BYTES + FLOAT64_LIMBS * FLOAT64_LIMB_BYTES;
